"""Publish benchmark folders authored in a harness; no benchmark editor here."""

import shutil
import tempfile
from pathlib import Path

import yaml

from .harnesses.base import select_harness
from .hub import cache_root, commit_files, download, hub_api, parse_reference
from .provenance import file_manifest, git_state


def split_card(text):
    if text.startswith("---\n"):
        pieces = text.split("\n---", 1)
        if len(pieces) != 2:
            raise ValueError("Unterminated dataset card front matter")
        metadata = yaml.safe_load(pieces[0][4:]) or {}
        if not isinstance(metadata, dict):
            raise ValueError("Dataset card front matter must be a mapping")
        return metadata, pieces[1].lstrip("\r\n")
    return {}, text


def hub_files(inspection, directory, previous=None, *, harness):
    raw = inspection["raw"]
    name = raw.get("title") or raw["name"]
    # The spec's top-level fields are fixed; like inspect-ai's solvers and scorers, what runs
    # and scores a task goes in the task. A copy per task keeps YAML anchors out of the file.
    tasks = [{**task, "harness": dict(harness)} for task in inspection["tasks"]]
    generated = {"name": name, "description": raw.get("description") or f"{name}, evaluated with cyclotron.",
                 "evaluation_framework": "cyclotron", "tasks": tasks}
    if previous and (previous / "eval.yaml").is_file():
        old = yaml.safe_load((previous / "eval.yaml").read_text())
        if not isinstance(old, dict) or not isinstance(old.get("tasks"), list):
            raise ValueError("Published eval.yaml is malformed")
        ids = {task["id"] for task in generated["tasks"]}
        generated["tasks"] = [*generated["tasks"], *(task for task in old["tasks"] if task["id"] not in ids)]
    readme = directory / "README.md"
    if not readme.is_file() and previous:
        readme = previous / "README.md"
    front, body = split_card(readme.read_text() if readme.is_file() else f"# {name}\n")
    card = {**front, **inspection["card"]}
    if "license" not in raw and not front.get("license"):
        raise ValueError("Set license in benchmark.yaml (an explicit blank means no license) before publishing")
    if "license" in raw:
        for key in ("license", "license_name", "license_link"):
            card.pop(key, None)
        card.update({key: value for key, value in inspection["card"].items() if key.startswith("license")})
    # The harness tags the card with its own name; the framework is cyclotron, so only the author's tags join it.
    own = list(raw.get("tags") or [])
    inherited = [tag for tag in front.get("tags", []) if tag != harness["name"] or tag in own]
    card["tags"] = list(dict.fromkeys(["cyclotron", *inherited, *own]))
    return {
        "eval.yaml": "# Generated by cyclotron from benchmark.yaml.\n" + yaml.safe_dump(generated, sort_keys=False),
        "README.md": "---\n" + yaml.safe_dump(card, sort_keys=False) + "---\n\n" + body,
    }


def version_check(current, previous):
    if not previous:
        return
    version, old = current["raw"]["version"], previous["raw"]["version"]
    if current["raw"]["name"] != previous["raw"]["name"]:
        raise ValueError("A published benchmark cannot change its name")
    if version < old:
        raise ValueError("Benchmark version cannot decrease")
    if current["scored_hash"] != previous["scored_hash"] and version <= old:
        raise ValueError("Scored benchmark content changed; increase benchmark.yaml version before publishing")


def ensure_tag(api, repo_id, sha, version):
    name = f"v{version}"
    tags = api.list_repo_refs(repo_id, repo_type="dataset").tags
    existing = next((tag for tag in tags if tag.name == name), None)
    if existing:
        if existing.target_commit != sha:
            raise ValueError(f"Tag {name} already identifies another commit; it will not be moved")
        print(f"Tag {name} already identifies {sha}")
        return
    api.create_tag(repo_id, tag=name, revision=sha, repo_type="dataset", tag_message=f"Benchmark {name}")
    print(f"Released {repo_id}@{name} ({sha})")


def publish(root, directory, repo_id, base=None, create=False, pr=False, dry_run=False, harness_name=None, api=None):
    from huggingface_hub.errors import RepositoryNotFoundError

    directory = Path(directory).expanduser().resolve()
    raw = yaml.safe_load((directory / "benchmark.yaml").read_text())
    if not isinstance(raw, dict):
        raise ValueError("benchmark.yaml must contain a mapping")
    harness = select_harness(root, harness_name, raw)
    harness.prepare()
    api = api or hub_api()
    target = parse_reference(repo_id, "dataset")
    if target["revision"] != "main":
        raise ValueError("Publish to a dataset ID, not a revision; use --base for an optimistic base check")
    repo_id = target["id"]
    previous = None
    try:
        info = api.repo_info(repo_id, repo_type="dataset", revision="main")
    except RepositoryNotFoundError as error:
        if not create or error.response is None or error.response.status_code != 404:
            raise
        info = None
    if create and info is not None:
        raise ValueError("--create requires a new repository; omit it to update an existing dataset")
    if base:
        if info is None or api.repo_info(repo_id, repo_type="dataset", revision=base).sha != info.sha:
            raise ValueError("--base must still identify the dataset's current main commit")
    if info:
        previous = Path(download({"id": repo_id, "repo_type": "dataset", "revision": info.sha}, harness.dataset_files, api)["path"])
    before = file_manifest(directory)
    temporary_root = cache_root() / "staging"
    temporary_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="publish-", dir=temporary_root) as temporary:
        staged = Path(temporary) / "benchmark"
        shutil.copytree(directory, staged, ignore=shutil.ignore_patterns(".*", "node_modules"))
        if file_manifest(staged) != before or file_manifest(directory) != before:
            raise ValueError("Benchmark folder changed while staging; save edits and retry")
        state = harness.state()
        inspection = harness.inspect_benchmark(staged, state["commit"])
        blockers = [*inspection["errors"], *inspection["problems"]]
        if state["dirty"] is not False or not state["commit"]:
            blockers.append("The harness checkout must have a known, clean commit")
        if inspection["public"] is not True:
            blockers.append("Harness commit is not on a fetched public upstream branch")
        cyclotron_state = git_state(root)
        if cyclotron_state["dirty"] is not False or not cyclotron_state["commit"]:
            blockers.append("The cyclotron checkout must have a known, clean commit for publication")
        old_inspection = harness.inspect_benchmark(previous) if previous else None
        version_check(inspection, old_inspection)
        generated = hub_files(inspection, staged, previous, harness=harness.task_harness(inspection, state["commit"]))
        files = {name: (staged / name).read_bytes() for name in inspection["files"] if name != "README.md"}
        files.update(generated)
        license_link = inspection["card"].get("license_link")
        if license_link and license_link not in files:
            raise ValueError("Use a publishable license filename, such as LICENSE or LICENSE.txt")
        if inspection["benchmark_yaml"]:
            files["benchmark.yaml"] = inspection["benchmark_yaml"]
        deletions = []
        if previous:
            deletions = sorted(set(harness.dataset_files(list(file_manifest(previous)))) - set(files))
        if file_manifest(directory) != before or harness.state() != state or git_state(root) != cyclotron_state:
            raise ValueError("Benchmark folder or code checkout changed during publication preparation")
        print(f"Publish {directory} -> datasets/{repo_id}")
        print(f"Parent: {info.sha if info else '(new private repo)'}; version: {inspection['raw']['version']}")
        print("Files: " + ", ".join(sorted(files)))
        if deletions:
            print("Remove obsolete dataset files: " + ", ".join(deletions))
        if dry_run:
            for name, text in generated.items():
                print(f"\n{name}:\n{text}")
            if blockers:
                print("Publication blockers:\n" + "\n".join(f"  - {item}" for item in blockers))
            print("Dry run: no remote writes. Hub framework registration/benchmark approval is required for publication.")
            return {"files": files, "deletions": deletions, "blockers": blockers}
        if blockers:
            raise ValueError("Cannot publish:\n" + "\n".join(blockers))
        if info is None:
            api.create_repo(repo_id, repo_type="dataset", private=True, exist_ok=False)
            info = api.repo_info(repo_id, repo_type="dataset", revision="main")
        result = commit_files(api, repo_id, files, info.sha, f"Publish {raw['name']} v{raw['version']}",
                              repo_type="dataset", pr=pr, deletions=deletions)
        print(f"Published: {result.pr_url or result.commit_url}")
        new_version = old_inspection is None or raw["version"] > old_inspection["raw"]["version"]
        if result.pr_url:
            print(f"After merging, run: ./cyclotron.sh --benchmark release {repo_id} <merged-commit>")
        elif new_version:
            try:
                ensure_tag(api, repo_id, result.oid, raw["version"])
            except Exception as error:
                raise ValueError(f"Commit succeeded ({result.commit_url}), but tagging failed: {error}. "
                                 f"Retry with: ./cyclotron.sh --benchmark release {repo_id} {result.oid}") from error
        return result


def release(root, repo_id, revision, dry_run=False, api=None):
    api = api or hub_api()
    target = parse_reference(repo_id, "dataset")
    repo_id = target["id"]
    if revision.startswith("refs/pr/"):
        raise ValueError("Release a merged main-branch revision, not a pending PR")
    info = api.repo_info(repo_id, repo_type="dataset", revision=revision)
    if info.sha not in {commit.commit_id for commit in api.list_repo_commits(repo_id, repo_type="dataset", revision="main")}:
        raise ValueError("Release revision is not in the dataset's main history")
    harness = select_harness(root)
    item = download({"id": repo_id, "repo_type": "dataset", "revision": info.sha}, harness.dataset_files, api)
    raw = yaml.safe_load((Path(item["path"]) / "benchmark.yaml").read_text())
    spec = yaml.safe_load((Path(item["path"]) / "eval.yaml").read_text())
    select_harness(root, benchmark=raw, spec=spec)
    if spec.get("evaluation_framework") != "cyclotron" or not raw.get("harness", {}).get("tested_commit"):
        raise ValueError("Revision is not a cyclotron-published benchmark with a tested harness commit")
    if not isinstance(raw.get("version"), int) or isinstance(raw["version"], bool) or raw["version"] < 1:
        raise ValueError("Invalid benchmark version")
    if dry_run:
        print(f"Would release datasets/{repo_id}@{info.sha} as v{raw['version']}; no remote writes")
    else:
        ensure_tag(api, repo_id, info.sha, raw["version"])
